/**
 * QUIRO — Isolated Local Test Database Setup Utility
 *
 * Sets up the dedicated `quiro_test` database on local MySQL (port 3306).
 *
 * STRICT SAFETY CONSTRAINTS:
 * 1. Only connects to localhost / 127.0.0.1 on port 3306.
 * 2. Strictly rejects any remote or cloud connection (never accesses TiDB Cloud).
 * 3. Never modifies the source local `quiro` database (read-only SELECT).
 * 4. Never exposes or logs credentials.
 */

const mysql = require('../server/node_modules/mysql2/promise');
const fs = require('fs');
const path = require('path');
const dotenv = require('../server/node_modules/dotenv');

async function setupTestDb() {
    console.log('================================================================');
    console.log('🛠️ QUIRO — ISOLATED LOCAL TEST DATABASE SETUP (`quiro_test`)');
    console.log('================================================================\n');

    // Load local credentials from server/.env safely
    const envPath = path.resolve(__dirname, '../server/.env');
    const parsed = fs.existsSync(envPath) ? dotenv.parse(fs.readFileSync(envPath)) : {};

    const host = parsed.LOCAL_DB_HOST || 'localhost';
    const port = parseInt(parsed.LOCAL_DB_PORT || '3306', 10);
    const user = parsed.LOCAL_DB_USER || 'root';
    const password = parsed.LOCAL_DB_PASSWORD || '';
    const sourceDb = parsed.LOCAL_DB_NAME || 'quiro';
    const targetDb = 'quiro_test';

    // 1. Hardened safety check on host
    const isLocal = host === 'localhost' || host === '127.0.0.1';
    if (!isLocal) {
        throw new Error(`[SAFETY GUARD] Setup rejected: Host '${host}' is not local! Refusing to execute.`);
    }

    if (port !== 3306) {
        throw new Error(`[SAFETY GUARD] Setup rejected: Port '${port}' is not local MySQL (3306).`);
    }

    console.log(`[Safety Guard] Target Host: ${host}:${port} (LOCAL CONFIRMED)`);
    console.log(`[Safety Guard] Source DB:   ${sourceDb}`);
    console.log(`[Safety Guard] Target DB:   ${targetDb}\n`);

    const conn = await mysql.createConnection({
        host,
        port,
        user,
        password,
        multipleStatements: true
    });

    try {
        // 2. Ensure target database exists
        console.log(`Creating database '${targetDb}' if not exists...`);
        await conn.query(`CREATE DATABASE IF NOT EXISTS \`${targetDb}\``);

        // 3. Get all tables from source database (quiro)
        const [tables] = await conn.query(`SHOW TABLES FROM \`${sourceDb}\``);
        const tableProp = Object.keys(tables[0])[0];
        const tableNames = tables.map(r => r[tableProp]);

        console.log(`Found ${tableNames.length} tables in source database '${sourceDb}'. Replicating to '${targetDb}'...`);

        // Disable foreign key checks during replication
        await conn.query(`SET FOREIGN_KEY_CHECKS = 0`);

        for (const tbl of tableNames) {
            // Drop existing table in test db if any, recreate structure like source, copy data
            await conn.query(`DROP TABLE IF EXISTS \`${targetDb}\`.\`${tbl}\``);
            await conn.query(`CREATE TABLE \`${targetDb}\`.\`${tbl}\` LIKE \`${sourceDb}\`.\`${tbl}\``);
            await conn.query(`INSERT INTO \`${targetDb}\`.\`${tbl}\` SELECT * FROM \`${sourceDb}\`.\`${tbl}\``);
        }

        // Restore foreign key checks
        await conn.query(`SET FOREIGN_KEY_CHECKS = 1`);

        // 4. Verify test database integrity
        const [testTables] = await conn.query(`SHOW TABLES FROM \`${targetDb}\``);
        const [userCount] = await conn.query(`SELECT COUNT(*) as c FROM \`${targetDb}\`.users`);
        const [bookCount] = await conn.query(`SELECT COUNT(*) as c FROM \`${targetDb}\`.books`);

        console.log(`\n✅ Replication complete:`);
        console.log(`   - Tables in '${targetDb}': ${testTables.length}`);
        console.log(`   - Users: ${userCount[0].c}`);
        console.log(`   - Books: ${bookCount[0].c}`);

        if (testTables.length !== tableNames.length) {
            throw new Error(`Table count mismatch! Expected ${tableNames.length}, got ${testTables.length}`);
        }

        // 5. Generate server/.env.test (strictly ignored by git)
        const testEnvFilePath = path.resolve(__dirname, '../server/.env.test');
        const testEnvContent = [
            '# QUIRO ISOLATED LOCAL TEST ENVIRONMENT',
            '# Auto-generated by scripts/setup-local-test-db.js — DO NOT COMMIT',
            'NODE_ENV=test',
            `DB_HOST=${host}`,
            `DB_PORT=${port}`,
            `DB_USER=${user}`,
            `DB_PASSWORD=${password}`,
            `DB_NAME=${targetDb}`,
            `TEST_DB_NAME=${targetDb}`,
            'DB_SSL=false',
            'PORT=5001',
            'TEST_PORT=5001',
            `JWT_SECRET=${parsed.JWT_SECRET || 'test_jwt_secret_for_quiro_testing_only_32_chars'}`,
            `RAZORPAY_KEY_ID=${parsed.RAZORPAY_KEY_ID || 'rzp_test_placeholder_key_id'}`,
            `RAZORPAY_KEY_SECRET=${parsed.RAZORPAY_KEY_SECRET || 'rzp_test_placeholder_secret'}`,
            'CLIENT_URL=http://localhost:5173',
            ''
        ].join('\n');

        fs.writeFileSync(testEnvFilePath, testEnvContent, 'utf8');
        console.log(`✅ Generated isolated test config: server/.env.test (git-ignored)`);

        console.log(`\n✨ '${targetDb}' is ready and fully isolated.\n`);
    } finally {
        await conn.end();
    }
}

if (require.main === module) {
    setupTestDb().catch(err => {
        console.error('❌ Test DB setup failed:', err.message);
        process.exit(1);
    });
}

module.exports = setupTestDb;
